"""Render docs/EVALUATION_REPORT.md from the evaluation outputs. No number in the report is typed by hand.

Inputs (all produced by the existing evaluation scripts, none by this one):
  outputs/evaluation/yolo_eagle_buildings-2_best_metrics.json   evaluation.verify_yolo
  outputs/evaluation/siamese_damage_metrics.json                evaluation.evaluate_siamese
  outputs/evaluation/pipeline_{practice,joint_val}_*.json       evaluation.evaluate_pipeline
  processed/siamese/pairs_{train,val}.csv                       class imbalance

    python -m evaluation.make_evaluation_report
"""
import csv
import json
import shutil
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EV = ROOT / "outputs" / "evaluation"
DOCS = ROOT / "docs"
CLASSES = ["no-damage", "minor-damage", "major-damage", "destroyed", "un-classified"]


def load(name):
    p = EV / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def labels(csv_path):
    with open(csv_path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return Counter(r["damage_name"] for r in rows), len({r["scene"] for r in rows})


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    yolo, sia = load("yolo_eagle_buildings-2_best_metrics.json"), load("siamese_damage_metrics.json")
    lines = ["# EAGLE-DAR model evaluation report", "",
             "Generated by `python -m evaluation.make_evaluation_report` from the evaluation output files. No model was retrained "
             "and no weights were changed. Nothing here is an official PS-04 score.", ""]

    # ---- data splits ----------------------------------------------------------------------------------------------
    lines += ["## 1. Which data each number comes from", ""]
    ptr, pva = ROOT / "processed/siamese/pairs_train.csv", ROOT / "processed/siamese/pairs_val.csv"
    if ptr.exists() and pva.exists():
        (ctr, str_), (cva, sva) = labels(ptr), labels(pva)
        lines += [md_table(["Split", "Used for", "Siamese building pairs", "Scenes"],
                           [["Training", "weight updates (Siamese)", f"{sum(ctr.values()):,}", str_],
                            ["Validation", "monitoring and **choosing the saved checkpoint** (lowest validation loss)", f"{sum(cva.values()):,}", sva]]), ""]
    lines += ["* **There is no independent test set.** The validation numbers below were also used to pick the checkpoint, so they are "
              "slightly optimistic. They are not training-set numbers.",
              "* The YOLO validation split (80 images, split by scene with a different random split) and the Siamese validation split are "
              "**different**: 55 of the 80 YOLO-validation scenes were Siamese *training* scenes. Whole-pipeline numbers therefore use only the "
              "scenes that are validation for **both** models (`joint_val`, 20 scenes) and the 40 PS-04 practice pairs, which neither model trained on.",
              "* The hidden PS-04 test data is not available, so the 86 % answer-accuracy target has **not** been evaluated and is not claimed.", ""]

    # ---- YOLO -----------------------------------------------------------------------------------------------------
    lines += ["## 2. Building detector (YOLOv8-seg), validation split", ""]
    if yolo:
        ck = yolo["checkpoint"]
        lines += [md_table(["Metric", "Boxes", "Masks"],
                           [["Precision", f"{yolo['box']['precision']:.3f}", f"{yolo['mask']['precision']:.3f}"],
                            ["Recall", f"{yolo['box']['recall']:.3f}", f"{yolo['mask']['recall']:.3f}"],
                            ["mAP50", f"{yolo['box']['mAP50']:.3f}", f"{yolo['mask']['mAP50']:.3f}"],
                            ["mAP50-95", f"{yolo['box']['mAP50_95']:.3f}", f"{yolo['mask']['mAP50_95']:.3f}"]]), "",
                  f"Weights: `{Path(yolo['weights']).name}` from the run `{Path(yolo['weights']).parent.parent.name}`; saved at epoch index "
                  f"{ck['epoch_index_saved']} of a run configured for {ck['train_args']['epochs']} epochs (the run stopped early, at epoch 16). "
                  "The model is weak: it finds roughly one building in five (mask recall), so building counts are strong under-estimates.", ""]
    else:
        lines += ["*Not available: run `python -m evaluation.verify_yolo`.*", ""]

    # ---- Siamese --------------------------------------------------------------------------------------------------
    lines += ["## 3. Damage classifier (Siamese ResNet18), validation split", ""]
    if sia:
        pc = sia["per_class"]
        lines += [f"Checkpoint `{Path(sia['checkpoint']).name}`, {sia['n_val']:,} validation building pairs.", "",
                  md_table(["Class", "Precision", "Recall", "F1", "Support"],
                           [[c, f"{pc[c]['precision']:.3f}", f"{pc[c]['recall']:.3f}", f"{pc[c]['f1-score']:.3f}", int(pc[c]['support'])] for c in CLASSES]), "",
                  md_table(["Overall", "Value"],
                           [["Accuracy", f"{sia['accuracy']:.4f}"], ["Macro F1 (5 classes)", f"{sia['macro_f1']:.4f}"],
                            ["Macro F1 excluding un-classified", f"{sia['macro_f1_excl_unclassified']:.4f}"],
                            ["Macro F1 on minor/major/destroyed only", f"{sia['macro_f1_damage_only_1_2_3']:.4f}"],
                            ["Weighted F1", f"{sia['weighted_f1']:.4f}"],
                            ["Validation loss (class-weighted CE / unweighted CE)", f"{sia['val_loss_weighted_ce']:.4f} / {sia['val_loss_unweighted_ce']:.4f}"]]), "",
                  "### Confusion matrix (rows = true class, columns = predicted)", "",
                  md_table(["true \\ pred"] + CLASSES, [[CLASSES[i]] + sia["confusion_matrix"]["rows_true_cols_pred"][i] for i in range(5)]), ""]
        png = EV / "siamese_damage_confusion_matrix.png"
        if png.exists():
            (DOCS / "figures").mkdir(exist_ok=True)
            shutil.copy(png, DOCS / "figures" / "siamese_confusion_matrix.png")
            lines += ["![Siamese confusion matrix](figures/siamese_confusion_matrix.png)", ""]
        total = sum(int(pc[c]["support"]) for c in CLASSES)
        maj = max(int(pc[c]["support"]) for c in CLASSES) / total
        pred = sia["pred_distribution"]
        lines += ["### What the numbers mean", "",
                  f"* **Accuracy ({sia['accuracy']:.3f}) is below the majority-class baseline ({maj:.3f})**: always answering \"no-damage\" would score higher. "
                  "Accuracy is not a useful summary here; macro F1 is.",
                  f"* The model **never predicts minor damage** ({pred['minor-damage']} predictions; recall {pc['minor-damage']['recall']:.2f}) and almost never major damage "
                  f"(recall {pc['major-damage']['recall']:.2f}). It over-predicts *destroyed* ({pred['destroyed']} predicted vs {int(pc['destroyed']['support'])} true; precision {pc['destroyed']['precision']:.2f}).",
                  "* Practical consequence: reports and maps under-report minor and major damage and over-report destroyed buildings; 'damaged' counts are dominated by the destroyed class.", ""]
        if ptr.exists():
            lines += ["### Class imbalance", "",
                      md_table(["Class", "Training pairs", "Training share", "Validation pairs", "Validation share"],
                               [[c, f"{ctr[c]:,}", f"{100 * ctr[c] / sum(ctr.values()):.1f}%", f"{cva[c]:,}", f"{100 * cva[c] / sum(cva.values()):.1f}%"] for c in CLASSES]), "",
                      "The training loss used square-root inverse-frequency class weights, which was not enough to make the rare classes learnable. "
                      "Likely remedies (not done, as retraining needs approval): stronger class weighting or focal loss, oversampling the three damage classes, "
                      "label-smoothing/ordinal loss, augmentation, and more epochs with early stopping on macro F1. The un-classified class has only 56 validation examples, so its metrics are very noisy.", ""]
    else:
        lines += ["*Not available: run `python -m evaluation.evaluate_siamese`.*", ""]

    # ---- pipeline -------------------------------------------------------------------------------------------------
    lines += ["## 4. Whole pipeline against ground-truth building polygons (IoU >= 0.5)", ""]
    rows = []
    for tag, name in (("PS-04 practice (40 pairs, never trained on)", "practice"), ("joint validation (20 scenes, validation for both models)", "joint_val")):
        for mode in ("check", "register"):
            d = load(f"pipeline_{name}_{mode}.json")
            if not d:
                continue
            det, dm = d["detection"], d.get("damage_on_matched") or {}
            rows.append([tag, mode, d["n_scenes"], f"{det['precision']:.3f}", f"{det['recall']:.3f}", f"{det['f1']:.3f}",
                         f"{dm.get('n', 0)}", f"{dm.get('accuracy', float('nan')):.3f}", f"{dm.get('macro_f1', float('nan')):.3f}"])
    if rows:
        lines += [md_table(["Set", "Alignment mode", "Scenes", "Det. precision", "Det. recall", "Det. F1", "Matched buildings", "Damage acc. (matched)", "Damage macro F1 (matched)"], rows), "",
                  "Detection recall is the limiting factor: the pipeline sees a small fraction of the true buildings. Damage metrics are computed only on buildings that were "
                  "matched, and for the practice set almost all matched buildings are no-damage, so macro F1 there reflects almost no damaged examples.", ""]
    else:
        lines += ["*Not available: run `python -m evaluation.evaluate_pipeline --set practice` and `--set joint_val`.*", ""]

    # ---- PS-04 ----------------------------------------------------------------------------------------------------
    key_f = ROOT / "dataset_source/practice/answers.jsonl"
    lines += ["## 5. PS-04 question answering (practice set, official key)", ""]
    if key_f.exists():
        key = {json.loads(l)["id"]: json.loads(l) for l in key_f.read_text(encoding="utf-8").splitlines() if l.strip()}
        rows = []
        for label, f in (("Ground-truth buildings (tests the reasoning logic only)", "practice_groundtruth_logic_check.jsonl"),
                         ("Trained models' predicted buildings (end to end)", "practice_model_submission.jsonl")):
            p_ = ROOT / "outputs/phase2" / f
            if not p_.exists():
                continue
            recs = [json.loads(l) for l in p_.read_text(encoding="utf-8").splitlines() if l.strip()]
            by = Counter(); ok = Counter()
            for r in recs:
                k = key.get(r["id"])
                if k:
                    by[k["type"]] += 1
                    ok[k["type"]] += r["answer"] == k["answer"]
            rows.append([label] + [f"{ok[t]}/{by[t]}" for t in (1, 2, 3, 4)] + [f"{sum(ok.values())}/{sum(by.values())} ({100 * sum(ok.values()) / max(sum(by.values()), 1):.0f}%)"])
        if rows:
            lines += [md_table(["Buildings come from", "Type 1 (count)", "Type 2 (quadrant)", "Type 3 (halves)", "Type 4 (unanswerable)", "All"], rows), ""]
    lines += ["Answer matches only: the scoring rule for evidence regions is unknown. With ground-truth buildings the three differences are unexplained discrepancies in the "
              "official key (documented in `docs/PHASE2_SPATIAL_RULES.md` and pinned in the tests). The large drop with predicted buildings is the building detector and classifier, not the "
              "reasoning engine. This is a practice-set measurement, not the hidden test, and **the 86 % target is not claimed**.", "",
              "## 6. Limitations of this evaluation", "",
              "* No independent test set; validation was used for checkpoint selection.",
              "* Few scenes (73 Siamese validation scenes, 80 YOLO validation images, 20 joint-validation scenes, 30 practice scenes): confidence intervals are wide.",
              "* Un-classified has 56 validation examples.", "* The 86 % PS-04 target is not evaluated or claimed.", ""]
    (DOCS / "EVALUATION_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print("Wrote", DOCS / "EVALUATION_REPORT.md")


if __name__ == "__main__":
    main()
